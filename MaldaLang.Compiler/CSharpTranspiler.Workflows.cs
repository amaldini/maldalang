        _output.AppendLine("var __compOutputJson = MaldaLang.BuiltIns.BuiltInFunctions.CallBuiltIn(\"toJSON\", new List<MaldaLang.Interpreter.RuntimeValue> { RuntimeHelpers.ToRuntimeValue(__compResult) }, null).AsString();");
