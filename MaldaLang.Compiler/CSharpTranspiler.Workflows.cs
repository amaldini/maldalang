        _output.AppendLine("finally");
        WriteIndent();
        _output.AppendLine("{");
        _indentLevel++;
        WriteIndent();
        _output.AppendLine("MaldaLang.BuiltIns.BuiltInFunctions.ExitTranspiledWorkflowContext();");
