        WriteIndent();
        _output.AppendLine("    if (right is int ri) { r = ri; return true; }");
        WriteIndent();
        _output.AppendLine("    r = 0;");
        WriteIndent();
        _output.AppendLine("    return false;");
        WriteIndent();
        _output.AppendLine("}");
