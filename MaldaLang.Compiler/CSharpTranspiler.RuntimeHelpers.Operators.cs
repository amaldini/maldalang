        _output.AppendLine("            ?? key.Item1.GetMethods(flags).FirstOrDefault(m =>");
        WriteIndent();
        _output.AppendLine("                m.Name == key.Item2 &&");
        WriteIndent();
        _output.AppendLine("                m.GetParameters().Length == 1 &&");
        WriteIndent();
